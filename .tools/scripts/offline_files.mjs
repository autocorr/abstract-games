// Write the list of files the service worker (sw.js) caches for offline play:
// every page, module, stylesheet, font and image the site loads. Run after
// adding, renaming or removing a site file; test/offline.test.js checks it.
//
//   node .tools/scripts/offline_files.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const EXTENSIONS = [".html", ".js", ".css", ".svg", ".woff2"];

export function siteFiles() {
  const out = ["index.html", "games.js"];
  const walk = (dir) => {
    for (const e of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
      const rel = `${dir}/${e.name}`;
      if (e.isDirectory()) walk(rel);
      else if (EXTENSIONS.includes(path.extname(e.name))) out.push(rel);
    }
  };
  walk("common");
  walk("games");
  return out.sort();
}

const START = "// BEGIN FILES (generated by .tools/scripts/offline_files.mjs)";
const END = "// END FILES";

export function listedFiles(src) {
  const body = src.slice(src.indexOf(START) + START.length, src.indexOf(END));
  return [...body.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = path.join(root, "sw.js");
  const src = fs.readFileSync(file, "utf8");
  const list = siteFiles().map((f) => `  "${f}",`).join("\n");
  const next = src.slice(0, src.indexOf(START) + START.length) +
    `\nconst FILES = [\n${list}\n];\n` + src.slice(src.indexOf(END));
  fs.writeFileSync(file, next);
  console.log(`sw.js: ${siteFiles().length} files`);
}
